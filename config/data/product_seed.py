def seed_list():
    """Deduplicate by company name (case-insensitive), keep first occurrence."""
    seen, out = set(), []
    for co, web, sec, city, ats in SEED:
        key = co.strip().lower()
        if key in seen:
            continue
        seen.add(key)
        out.append({"company": co, "website": web, "sector": sec, "city": city, "ats": ats})
    return out


